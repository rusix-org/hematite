    assert!(K_GPRS.is_multiple_of(8));
    assert!(K_Q.is_multiple_of(8));
    assert!(K_FPCR.is_multiple_of(8));
    assert!(K_FPSR.is_multiple_of(8));
    assert!(DEADLINE.is_multiple_of(8));
    assert!(ACTIVE.is_multiple_of(8));
