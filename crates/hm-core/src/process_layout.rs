    assert!(GICD_CTL.is_multiple_of(8));
    assert!(GICC_CTL.is_multiple_of(8));
    assert!(GIC_PMR.is_multiple_of(8));
    assert!(GIC_BPR.is_multiple_of(8));
    assert!(GIC_GROUP.is_multiple_of(8));
    assert!(GIC_CONFIG.is_multiple_of(8));
    assert!(GIC_PRIORITY.is_multiple_of(8));
    assert!(GIC_ENABLE.is_multiple_of(8));
    assert!(TIMER_STATUS.is_multiple_of(8));
    assert!(TRAP_COUNT.is_multiple_of(8));
    assert!(K_TCR.is_multiple_of(8));
    assert!(K_MAIR.is_multiple_of(8));
    assert!(ROOT.is_multiple_of(8));
    assert!(FEATURES == ROOT + 8 && K_DIT == FEATURES + 8 && K_SSBS == K_DIT + 8);
    assert!(FRAME_SIZE.is_multiple_of(8));
